"""A catalog as Markdown tables: the answers grouped by the area of their question, the
divergences, the defects and the error classes. Every cell is a field of a record."""
from __future__ import annotations

import enum

from ganda.core.rules.model import IR, Campaign, Catalog, Finding, Standard, Tck, VendorDoc, Verdict


def value_text(v, error: "int | None" = None) -> str:
    if v is None:
        return ""
    if isinstance(v, bool):
        return "true" if v else "false"
    if isinstance(v, enum.Enum):
        text = str(v.value)
        return f"{text} [{error}]" if v is Verdict.REFUSED and error is not None else text
    if isinstance(v, tuple):
        return "(" + ", ".join(value_text(x) for x in v) + ")"
    return str(v)


def ref_text(r) -> str:
    if isinstance(r, Standard):
        return f"{r.document} §{r.section}"
    if isinstance(r, Tck):
        return f"openCypher TCK {r.feature} #{r.scenario}"
    if isinstance(r, VendorDoc):
        return f"{r.document} ({r.edition})" + (f": {r.topic}" if r.topic else "")
    if isinstance(r, Finding):
        return f"finding {r.id}"
    if isinstance(r, Campaign):
        return f"campaign {r.tag}"
    raise TypeError(r)


def _cell(s: str) -> str:
    return s.replace("|", "\\|")


def _table(header: list, rows: list) -> list:
    out = ["| " + " | ".join(header) + " |", "|" + "---|" * len(header)]
    out += ["| " + " | ".join(_cell(c) for c in row) + " |" for row in rows]
    return out


def _subject(language, data_model) -> str:
    return f"{language.value}" + (f" ({data_model})" if data_model else "")


def _by_area(catalog: Catalog) -> list:
    """(area, answers): the areas in the catalog's order (the IR's answers placed with the
    questions they answer), each question's answers together, the IR's first, then the
    languages in their declared order."""
    order = {lang: i for i, lang in enumerate(catalog.languages)}
    questions: dict = {}
    for a in sorted(catalog.answers, key=lambda a: a.language is IR):
        questions.setdefault(a.question.name, []).append(a)
    areas: dict = {}
    for name, answers in questions.items():
        answers.sort(key=lambda a: (-1 if a.language is IR else order[a.language], a.data_model or ""))
        areas.setdefault(name.split(".", 1)[0], []).extend(answers)
    return list(areas.items())


def render(catalog: Catalog) -> str:
    lines = [f"# {catalog.engine}: engine rules", "", "<!-- generated by `ganda {0} rules --write`; edit `ganda/{0}/rules/` -->".format(catalog.engine), ""]
    for area, answers in _by_area(catalog):
        lines += [f"## {area}", ""]
        rows = [[a.question.name, _subject(a.language, a.data_model), value_text(a.value, a.error), a.basis.value, ", ".join(a.facts), "; ".join(ref_text(r) for r in a.refs), value_text(a.documented), value_text(a.standard)] for a in answers]
        lines += _table(["question", "language", "answer", "basis", "probe facts", "evidence", "documented", "standard"], rows) + [""]
    divergent = catalog.divergences()
    if divergent:
        lines += ["## divergences", ""]
        rows = [[q.name, "; ".join(f"{_subject(a.language, a.data_model)}: {value_text(a.value, a.error)}" for a in answers)] for q, answers in divergent]
        lines += _table(["question", "answers"], rows) + [""]
    if catalog.defects:
        lines += ["## defects", ""]
        rows = [[d.id, ", ".join(d.aliases), _subject(d.language, d.data_model), d.trigger, d.effect.value + (f" [{d.error}]" if d.error is not None else ""), d.handling.value, ", ".join(d.facts), "; ".join(ref_text(r) for r in d.refs)] for d in catalog.defects]
        lines += _table(["id", "aliases", "language", "trigger", "effect", "handling", "probe facts", "evidence"], rows) + [""]
    if catalog.errors:
        lines += ["## error classes", ""]
        rows = [[e.kind.value, ", ".join(str(c) for c in sorted(e.codes)) or "any", "; ".join(f"`{m}`" for m in e.marks), ", ".join(e.facts)] for e in catalog.errors]
        lines += _table(["class", "codes", "message marks", "probe facts"], rows) + [""]
    return "\n".join(lines)
