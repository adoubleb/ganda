"""A catalog as Markdown tables: the rules by kind with the probe facts that check them,
the divergences, the defects with the facts that reproduce them, and the error classes;
with a baseline (`ganda.core.rules.baseline`), the build the probe last verified and the
defects fixed there."""
from __future__ import annotations

import enum

from ganda.core.rules.model import IR, Catalog, Kind


def value_text(v) -> str:
    if isinstance(v, bool):
        return "true" if v else "false"
    if isinstance(v, enum.Enum):
        return str(v.value)
    if isinstance(v, str):
        return f"`{v}`"
    return repr(v) if isinstance(v, float) else str(v)


def _cell(s: str) -> str:
    return s.replace("|", "\\|")


def _table(header: list, rows: list) -> list:
    out = ["| " + " | ".join(header) + " |", "|" + "---|" * len(header)]
    out += ["| " + " | ".join(_cell(c) for c in row) + " |" for row in rows]
    return out


def _ordered(catalog: Catalog, kind: Kind) -> list:
    """The rules of one kind: each question's rules together, the IR's first, then the
    subjects in their declared order."""
    order = {s: i for i, s in enumerate(catalog.subjects)}
    rules = [r for r in catalog.rules if r.question.kind is kind]
    first: dict = {}
    for i, r in enumerate(rules):
        first.setdefault(r.question.name, i)
    return sorted(rules, key=lambda r: (first[r.question.name], -1 if r.subject is IR else order[r.subject]))


def _sites(reads: list, strip: str) -> str:
    return ", ".join(f"{r.path.removeprefix(strip)}:{r.line}" for r in reads)


def _probed(catalog: Catalog, base: dict) -> str:
    if not base:
        return "baseline: none (no probe run has held on every check of a rule)"
    ran = set(base["held"]) | {f for fids in base["fixed"].values() for f in fids}
    ids = [fid for fid in catalog.checks if fid not in ran]
    return f"baseline: {base['version']}, every check of a rule held" + (f"; not run there: {', '.join(ids)}" if ids else "")


def _status(catalog: Catalog, defect, base: dict) -> str:
    """A defect on the baseline's build: reproduces, fixed, or fixed in the faces named."""
    fixed = base["fixed"].get(defect.id, [])
    if not fixed:
        return "reproduces"
    return "fixed" if set(fixed) == set(catalog.checked_by(defect)) else "fixed: " + ", ".join(fixed)


def render(catalog: Catalog, read_by: "dict | None" = None, strip: str = "", baseline: "dict | None" = None) -> str:
    """The tables; with `read_by` (`lookup.read_by`) a column of the code reading each
    rule and defect (its paths without the prefix `strip`); with `baseline`
    (`Baseline.read`), the build the probe last verified and each defect's state there."""
    lines = [f"# {catalog.engine}: engine rules", "", "<!-- generated by `ganda {0} rules --write` from `ganda/{0}/rules/` -->".format(catalog.engine), ""]
    if baseline is not None:
        lines += [_probed(catalog, baseline), ""]
    for kind in Kind:
        rules = _ordered(catalog, kind)
        if not rules:
            continue
        lines += [f"## {kind.value}", ""]
        rows = [[r.question.name, r.subject.value, value_text(r.answer), "definition" if r.subject is IR else (", ".join(catalog.checked_by(r)) or "unchecked")] for r in rules]
        header = ["question", "subject", "answer", "checked by"]
        if read_by is not None:
            header.append("read by")
            for row, r in zip(rows, rules):
                row.append(_sites(read_by["rules"].get((r.question.name, r.subject), []), strip) or "unread")
        lines += _table(header, rows) + [""]
    divergent = catalog.divergences()
    if divergent:
        lines += ["## divergences", ""]
        rows = [[q.name, "; ".join(f"{r.subject.value}: {value_text(r.answer)}" for r in rules)] for q, rules in divergent]
        lines += _table(["question", "answers"], rows) + [""]
    if catalog.defects:
        lines += ["## defects", ""]
        rows = [[d.id, d.subject.value, ", ".join(catalog.checked_by(d)) or "unchecked"] for d in catalog.defects]
        header = ["id", "subject", "reproduced by"]
        if baseline:
            header.append(f"on {baseline['version']}")
            for row, d in zip(rows, catalog.defects):
                row.append(_status(catalog, d, baseline))
        if read_by is not None:
            header.append("read by")
            for row, d in zip(rows, catalog.defects):
                row.append(_sites(read_by["defects"].get(d.id, []), strip) or "unread")
        lines += _table(header, rows) + [""]
    if catalog.errors:
        lines += ["## error classes", ""]
        rows = [[e.kind.value, ", ".join(str(c) for c in sorted(e.codes)) or "any", (" and " if e.all_marks else "; ").join(f"`{m}`" for m in e.marks) + (" (any case)" if e.marks and e.ignore_case else ""), ", ".join(catalog.checked_by(e)) or "unchecked"] for e in catalog.errors]
        lines += _table(["class", "codes", "message marks", "checked by"], rows) + [""]
    ir = sum(1 for r in catalog.rules if r.subject is IR)
    unchecked = len(catalog.unchecked())
    summary = f"{len(catalog.rules)} rules ({ir} IR definitions): {len(catalog.rules) - ir - unchecked} checked by a probe fact, {unchecked} unchecked"
    if read_by is not None:
        unread = sum(1 for r in catalog.rules if r.subject is not IR and not read_by["rules"].get((r.question.name, r.subject)))
        summary += f"; {len(catalog.rules) - ir - unread} read by code, {unread} unread"
    unreproduced = len(catalog.unreproduced())
    lines += [summary + f"; {len(catalog.defects)} defects ({len(catalog.defects) - unreproduced} reproduced by a probe fact); {len(catalog.errors)} error classes", ""]
    return "\n".join(lines)
